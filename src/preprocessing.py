"""
Модуль предобработки текста.

Что здесь происходит:
1. Текст делится на предложения (split_sentences).
2. Каждое предложение делится на слова (tokenize).
3. Из слов убираются «стоп-слова» — служебные слова без смысла (и, в, на, что...).
4. Слова приводятся к основе (stem): «графы», «графа», «графом» -> «граф».

Автор модуля: Арина
"""

import re

# ---------------------------------------------------------------------------
# 1. Деление текста на предложения
# ---------------------------------------------------------------------------

# Сокращения, после которых точка НЕ означает конец предложения.
ABBREVIATIONS = [
    "т. е.", "т.е.", "т. д.", "т.д.", "т. п.", "т.п.", "т. к.", "т.к.",
    "и др.", "и пр.", "др.", "пр.", "см.", "ср.", "рис.", "табл.",
    "г.", "гг.", "в.", "вв.", "н. э.", "н.э.", "до н. э.",
    "млн.", "млрд.", "тыс.", "руб.", "коп.", "км.", "им.", "ул.", "проф.",
]

_PLACEHOLDER = "<ТОЧКА>"


def split_sentences(text):
    """Делит текст на список предложений.

    Правило простое: предложение заканчивается на . ! ? или …,
    после которых идёт пробел и заглавная буква (или кавычка/цифра).
    Точки внутри сокращений («т. е.», «2020 г.») временно прячем,
    чтобы они не разрывали предложение.
    """
    text = re.sub(r"\s+", " ", text.strip())  # убираем лишние пробелы и переносы

    # прячем точки в сокращениях
    for abbr in sorted(ABBREVIATIONS, key=len, reverse=True):
        text = text.replace(" " + abbr, " " + abbr.replace(".", _PLACEHOLDER))
    # прячем точки в инициалах: «А. С. Пушкин»
    text = re.sub(r"\b([А-ЯЁA-Z])\.(?=\s?[А-ЯЁA-Z])", r"\1" + _PLACEHOLDER, text)

    # режем по концу предложения
    parts = re.split(r"(?<=[.!?…])\s+(?=[«\"(А-ЯЁA-Z0-9])", text)

    sentences = []
    for part in parts:
        part = part.replace(_PLACEHOLDER, ".").strip()
        if len(part) > 1:
            sentences.append(part)
    return sentences


# ---------------------------------------------------------------------------
# 2. Деление предложения на слова
# ---------------------------------------------------------------------------

def tokenize(sentence):
    """Возвращает список слов в нижнем регистре (без знаков препинания)."""
    sentence = sentence.lower().replace("ё", "е")
    return re.findall(r"[а-яa-z0-9]+(?:-[а-яa-z0-9]+)*", sentence)


# ---------------------------------------------------------------------------
# 3. Стоп-слова
# ---------------------------------------------------------------------------

STOPWORDS = set("""
а без более больше будет будто бы был была были было быть в вам вас ведь весь во вот
впрочем все всегда всего всех всю вы где да даже два для до другой его ее ей ему если
есть еще ж же за зачем здесь и из или им иногда их к как какая какой когда конечно кто
куда ли лучше между меня мне много может можно мой моя мы на над надо наконец нас не
него нее ней нельзя нет ни нибудь никогда ним них ничего но ну о об один он она они
опять от перед по под после потом потому почти при про раз разве с сам свое свою себе
себя сейчас со совсем так такой там тебя тем теперь то тогда того тоже только том тот
три тут ты у уж уже хорошо хоть чего чем через что чтоб чтобы чуть эти этого этой этом
этот эту я также который которая которое которые которых котором которой которую
этих это эта свой своих своей своего своим является являются однако лишь очень
каждый каждого каждой между весьма именно поэтому таким такие такая такое таких
""".split())


def remove_stopwords(words):
    """Убирает служебные слова и слишком короткие слова (1 буква)."""
    return [w for w in words if w not in STOPWORDS and len(w) > 1]


# ---------------------------------------------------------------------------
# 4. Упрощённый стеммер для русского языка
# ---------------------------------------------------------------------------
# Настоящий стеммер Портера (Snowball) сложнее. Мы используем упрощённую
# версию: отрезаем самое длинное подходящее окончание, но оставляем
# в слове не меньше 3 букв. Для задачи сравнения предложений этого хватает.

ENDINGS = sorted("""
ыми ими ого его ому ему ая яя ою ею ой ей ий ый ое ее ые ие ую юю ом ем ым им их ых
ами ями ах ях ам ям ов ев ей ию ия ие ии ью ья ье ьи ь ы и а я о е у ю й
ться тся ить ать ять еть уть ешь ете ите ишь ет ит ут ют ат ят ал ял ил ыл ла ли ло
ающий ающая ающее ающие ующий ующая ующее ующие ённый енный анный ость ости остью
ание ания анием ение ения ением ений аний ировать ировал ирует ируют
ется ются ится ятся алась ились алось ался ился ся сь
""".split(), key=len, reverse=True)


def stem(word):
    """Отрезает окончание у русского слова. Английские слова и числа не трогаем."""
    if not re.match(r"^[а-я]+$", word) or len(word) <= 4:
        return word
    for ending in ENDINGS:
        if word.endswith(ending) and len(word) - len(ending) >= 3:
            return word[: -len(ending)]
    return word


# ---------------------------------------------------------------------------
# Всё вместе
# ---------------------------------------------------------------------------

def preprocess(text):
    """Полная предобработка.

    Возвращает два списка одинаковой длины:
      sentences — исходные предложения (их потом покажем в реферате);
      tokens    — для каждого предложения список очищенных основ слов.
    """
    sentences = split_sentences(text)
    tokens = [[stem(w) for w in remove_stopwords(tokenize(s))] for s in sentences]
    return sentences, tokens


